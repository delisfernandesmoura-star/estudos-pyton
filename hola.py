# Tudo que começa com o símbolo "#" é um COMENTÁRIO.
# O computador ignora essas linhas. Elas servem só para nós, humanos, lermos.

# A linha abaixo é a única que o computador realmente executa:
print("Olá, Délis.")

# Explicando, pedaço por pedaço:
#   print      -> é um comando do Python que significa "mostre na tela".
#   ( )        -> os parênteses guardam o que queremos mostrar.
#   " "        -> as aspas dizem ao Python: "isto é um texto, mostre exatamente assim".
#   Olá, Délis. -> é o texto que vai aparecer na tela.
#
# Como rodar este arquivo:
#   1. Abra o terminal na pasta onde está este arquivo.
#   2. Digite:  python hola.py   (ou python3 hola.py)
#   3. Aperte Enter. Vai aparecer na tela:  Olá, Délis.
